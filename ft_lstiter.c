#include "libft.h"

/*
PROTOTYPE
----------
		void ft_lstiter(t_list *lst, void (*f)(void *));

RETURNS
----------
		Nothing (void).

DESCRIPTION
----------
		Iterates through a linked list and applies
		the function f to each node's content.
*/
void	ft_lstiter(t_list *lst, void (*f)(void *))
{
	if (!lst || !f)
		return ;
	while (lst)
	{
		f(lst->content);
		lst = lst->next;
	}
}
